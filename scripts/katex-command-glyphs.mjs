// Generates src/markdown/katex-command-glyphs.js from KaTeX's own symbol and
// macro tables, so the math-compact key reads a TeX symbol command as the
// glyph KaTeX prints for it, which is the glyph a PDF text layer keeps.
//
//   node scripts/katex-command-glyphs.mjs
//
// test/katex-command-glyphs.test.js compares the committed table with the
// installed KaTeX, so a KaTeX upgrade that changes a symbol fails there
// until this script is run again.

import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

// Atom groups whose symbol is one glyph in the PDF text layer. Accents sit on
// another letter, delimiters stretch or are built from pieces, and spacing
// prints nothing, so those groups stay out of the table.
const INCLUDED_GROUPS = new Set([
    'bin',
    'mathord',
    'op',
    'punct',
    'rel',
    'textord',
]);

const COMMAND_NAME = /^\\[A-Za-z]+$/u;
const DEFINE_SYMBOL = /defineSymbol\(\s*math\s*,\s*\w+\s*,\s*(\w+)\s*,\s*("(?:[^"\\]|\\.)*")\s*,\s*("(?:[^"\\]|\\.)*")/gu;
const DEFINE_MACRO = /defineMacro\(\s*("(?:[^"\\]|\\.)*")\s*,\s*("(?:[^"\\]|\\.)*")\s*\)/gu;
// Wrappers a macro body puts around the one symbol it prints.
const MACRO_WRAPPER = /\\(?:DOTS[BIX]|mathrel|mathbin|mathop|mathord|mathpunct|[,;:!])(?![A-Za-z])/gu;

/**
 * Every TeX command KaTeX prints as one glyph in math mode, as a Map from the
 * command name without its backslash to that glyph.
 */
export async function readKatexCommandGlyphs({
    symbolsPath = require.resolve('katex/src/symbols.ts'),
    macrosPath = require.resolve('katex/src/macros.ts'),
} = {}) {
    const glyphs = new Map();
    const symbolSource = await readFile(symbolsPath, 'utf8');
    for (const match of symbolSource.matchAll(DEFINE_SYMBOL)) {
        const group = match[1];
        const glyph = parseLiteral(match[2]);
        const name = parseLiteral(match[3]);
        if (!INCLUDED_GROUPS.has(group)
            || !COMMAND_NAME.test(name || '')
            || !isOneGlyph(glyph)
            || glyphs.has(name)) {
            continue;
        }
        glyphs.set(name, glyph);
    }

    // A macro is expanded before a symbol is looked up, so it decides what a
    // name prints: an alias of one symbol, or one glyph in its MathML branch.
    const macroSource = await readFile(macrosPath, 'utf8');
    for (const match of macroSource.matchAll(DEFINE_MACRO)) {
        const name = parseLiteral(match[1]);
        const body = parseLiteral(match[2]);
        if (!COMMAND_NAME.test(name || '') || body === null) continue;
        const glyph = macroGlyph(body, glyphs);
        if (glyph) glyphs.set(name, glyph);
        else glyphs.delete(name);
    }

    return new Map([...glyphs]
        .map(([name, glyph]) => [name.slice(1), glyph])
        .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0)));
}

function macroGlyph(body, symbols) {
    const mathML = /^\\html@mathml\{.*\}\{(.*)\}$/u.exec(body);
    const printed = (mathML ? mathML[1] : body)
        .replace(MACRO_WRAPPER, '')
        .replace(/\\char`/gu, '')
        .replace(/[{}\s]/gu, '');
    if (COMMAND_NAME.test(printed)) return symbols.get(printed) || null;
    return isOneGlyph(printed) && !/[A-Za-z0-9\\]/u.test(printed)
        ? printed
        : null;
}

function parseLiteral(literal) {
    try {
        return JSON.parse(literal);
    }
    catch {
        return null;
    }
}

function isOneGlyph(value) {
    return typeof value === 'string' && [...value].length === 1;
}

function sourceLiteral(value) {
    return `'${[...value].map(character => (
        /[\p{L}\p{N}\p{S}\p{P}]/u.test(character) && !/['\\]/u.test(character)
            ? character
            : `\\u{${character.codePointAt(0).toString(16).toUpperCase()}}`
    )).join('')}'`;
}

async function main() {
    const { version } = require('katex/package.json');
    const glyphs = await readKatexCommandGlyphs();
    const lines = [...glyphs].map(([name, glyph]) => (
        `    [${sourceLiteral(name)}, ${sourceLiteral(glyph)}],`
    ));
    const output = [
        `// Generated by scripts/katex-command-glyphs.mjs from KaTeX ${version}.`,
        '// Do not edit by hand; run the script after a KaTeX upgrade.',
        '//',
        '// Every TeX command KaTeX prints as one glyph in math mode, without its',
        '// backslash, mapped to that glyph.',
        'export const KATEX_COMMAND_GLYPHS = new Map([',
        ...lines,
        ']);',
        '',
    ].join('\n');
    const target = fileURLToPath(new URL(
        '../src/markdown/katex-command-glyphs.js',
        import.meta.url
    ));
    await writeFile(target, output);
    console.log(`Wrote ${glyphs.size} commands to ${target}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    await main();
}
